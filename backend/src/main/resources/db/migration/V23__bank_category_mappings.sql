-- AP 28b (R33, decision 63): the user's confirmed mapping of a bank category to an own category, per bank. It goes
-- with its category: deleting the category deletes the mapping (so deleting an account needs no extra step).
-- Never change this file once merged.
create table bank_category_mappings (
    id            bigint generated by default as identity,
    owner_id      bigint       not null,
    profile       varchar(20)  not null,
    bank_category varchar(100) not null,
    category_id   bigint       not null,
    constraint pk_bank_category_mappings primary key (id),
    constraint fk_bank_category_mappings_owner foreign key (owner_id) references users (id),
    constraint fk_bank_category_mappings_category foreign key (category_id) references category (id) on delete cascade,
    constraint uk_bank_category_mappings unique (owner_id, profile, bank_category)
);
