-- Passkeys (US44, AP 34, decision 96): sign-in with a passkey in addition to the password. A user gets a random
-- WebAuthn user handle on the first passkey; it holds no personal data and stays when the e-mail changes. Each passkey
-- stores only its public key (COSE) and the attestation object of the registration, all base64url, never a secret.
-- Never change this file once merged.

alter table users add column passkey_user_handle varchar(100);
alter table users add constraint uk_users_passkey_user_handle unique (passkey_user_handle);

create table passkeys (
    id                  bigint generated by default as identity,
    user_id             bigint                   not null,
    credential_id       varchar(1400)            not null,
    public_key          varchar(2000)            not null,
    attestation_object  varchar(4000)            not null,
    signature_count     bigint                   not null,
    uv_initialized      boolean                  not null,
    backup_eligible     boolean                  not null,
    backup_state        boolean                  not null,
    transports          varchar(200)             not null,
    label               varchar(50)              not null,
    created_at          timestamp with time zone not null,
    last_used_at        timestamp with time zone,
    constraint pk_passkeys primary key (id),
    constraint uk_passkeys_credential_id unique (credential_id),
    constraint fk_passkeys_user foreign key (user_id) references users (id)
);

create index ix_passkeys_user on passkeys (user_id);
