-- Plan and actuals (section 19, AP 27b): planned items replace series and category targets, terms replace the
-- exceptions of a series. A change "from month" is a new version with the same item_key. The data of the old tables
-- is converted by the Java migration V14; V15 drops them. Never change this file once merged.

create table planned_items (
    id            bigint generated by default as identity,
    owner_id      bigint         not null,
    item_key      uuid           not null,
    name          varchar(100)   not null,
    amount        numeric(12, 2) not null,
    saving        boolean        not null default false,
    category_id   bigint,
    account_id    bigint         not null,
    rhythm_unit   varchar(5),
    rhythm_count  integer,
    anchor_date   date,
    entry_mode    varchar(6)     not null,
    workdays_only boolean        not null default false,
    valid_from    date           not null,
    valid_to      date,
    -- R31: the import that created the item; undoing the import deletes it (US34)
    import_batch_id bigint,
    constraint pk_planned_items primary key (id),
    constraint fk_planned_items_owner foreign key (owner_id) references users (id),
    constraint fk_planned_items_category foreign key (category_id) references category (id),
    constraint fk_planned_items_account foreign key (account_id) references bank_accounts (id),
    constraint fk_planned_items_import_batch foreign key (import_batch_id) references import_batches (id),
    constraint ck_planned_items_rhythm check (
        (rhythm_unit is null and rhythm_count is null and anchor_date is null)
        or (rhythm_unit in ('WEEK', 'MONTH') and rhythm_count >= 1 and anchor_date is not null)),
    constraint ck_planned_items_entry_mode check (entry_mode in ('AUTO', 'TICK', 'MANUAL')),
    constraint ck_planned_items_category check (saving or category_id is not null)
);
create index ix_planned_items_owner on planned_items (owner_id);
create index ix_planned_items_key on planned_items (item_key);

create table item_terms (
    id             bigint generated by default as identity,
    owner_id       bigint  not null,
    item_key       uuid    not null,
    term_date      date    not null,
    transaction_id bigint,
    skipped        boolean not null default false,
    constraint pk_item_terms primary key (id),
    constraint fk_item_terms_owner foreign key (owner_id) references users (id),
    constraint fk_item_terms_transaction foreign key (transaction_id) references transactions (id) on delete set null,
    constraint uk_item_terms_key_date unique (item_key, term_date),
    constraint uk_item_terms_transaction unique (transaction_id)
);
create index ix_item_terms_owner on item_terms (owner_id);

