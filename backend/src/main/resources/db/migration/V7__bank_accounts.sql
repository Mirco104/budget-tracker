-- Bank accounts (R26, US30, AP 26b). Every transaction and series belongs to one account of its owner. Every
-- existing user gets the account "Girokonto" as default account, and all existing entries move onto it.
-- Exactly one default account per user is enforced by the service. Never change this file once merged.

create table bank_accounts (
    id              bigint generated by default as identity,
    owner_id        bigint      not null,
    name            varchar(50) not null,
    iban            varchar(34),
    default_account boolean     default false not null,
    archived        boolean     default false not null,
    constraint pk_bank_accounts primary key (id),
    constraint fk_bank_accounts_owner foreign key (owner_id) references users (id),
    -- The service also ignores case for names
    constraint uk_bank_accounts_owner_name unique (owner_id, name),
    constraint uk_bank_accounts_owner_iban unique (owner_id, iban)
);

insert into bank_accounts (owner_id, name, default_account, archived)
select id, 'Girokonto', true, false from users;

alter table transactions add column account_id bigint;
update transactions set account_id =
    (select b.id from bank_accounts b where b.owner_id = transactions.owner_id and b.default_account = true);
alter table transactions alter column account_id set not null;
alter table transactions add constraint fk_transactions_account foreign key (account_id) references bank_accounts (id);
create index ix_transactions_account on transactions (account_id);

alter table recurring_transactions add column account_id bigint;
update recurring_transactions set account_id =
    (select b.id from bank_accounts b where b.owner_id = recurring_transactions.owner_id and b.default_account = true);
alter table recurring_transactions alter column account_id set not null;
alter table recurring_transactions
    add constraint fk_recurring_transactions_account foreign key (account_id) references bank_accounts (id);
create index ix_recurring_transactions_account on recurring_transactions (account_id);
