-- Bank CSV import (R30, US33, US34, AP 26e). An import is a batch; its transactions remember the batch, the
-- fingerprint of their row (unique per user, so a row is never imported twice), the counterparty and the bank's
-- category (for the suggestion, R29). An account remembers the sources of bank files it was chosen for.
-- Never change this file once merged.

create table import_batches (
    id         bigint generated by default as identity,
    owner_id   bigint                   not null,
    profile    varchar(20)              not null,
    created_at timestamp with time zone not null,
    first_date date                     not null,
    last_date  date                     not null,
    row_count  integer                  not null,
    constraint pk_import_batches primary key (id),
    constraint fk_import_batches_owner foreign key (owner_id) references users (id)
);
create index ix_import_batches_owner on import_batches (owner_id);

alter table transactions add column import_batch_id bigint;
alter table transactions add column fingerprint varchar(64);
alter table transactions add column counterparty varchar(100);
alter table transactions add column bank_category varchar(100);
alter table transactions
    add constraint fk_transactions_import_batch foreign key (import_batch_id) references import_batches (id);
-- Several transactions without fingerprint are allowed: NULL is never equal in a unique constraint
alter table transactions add constraint uk_transactions_owner_fingerprint unique (owner_id, fingerprint);
create index ix_transactions_import_batch on transactions (import_batch_id);

create table bank_account_sources (
    id         bigint generated by default as identity,
    owner_id   bigint       not null,
    account_id bigint       not null,
    source_key varchar(120) not null,
    constraint pk_bank_account_sources primary key (id),
    constraint fk_bank_account_sources_owner foreign key (owner_id) references users (id),
    constraint fk_bank_account_sources_account foreign key (account_id) references bank_accounts (id),
    constraint uk_bank_account_sources_owner_key unique (owner_id, source_key)
);
