-- Accounts (AP 27f, concept 3.4, P1, P11): every account has a role, balances from the bank are stored per day, a
-- transfer to a savings or depot account is the kind Sparen, and a reserve pot can be linked to a savings account.
-- All existing accounts start as Alltag (concept section 7). Never change this file once merged.

alter table bank_accounts add column role varchar(8) default 'EVERYDAY' not null;
alter table bank_accounts add constraint ck_bank_accounts_role check (role in ('EVERYDAY', 'SAVINGS', 'DEPOT'));

create table account_balances (
    id           bigint generated by default as identity,
    owner_id     bigint         not null,
    account_id   bigint         not null,
    balance_date date           not null,
    amount       numeric(12, 2) not null,
    constraint pk_account_balances primary key (id),
    constraint fk_account_balances_owner foreign key (owner_id) references users (id),
    constraint fk_account_balances_account foreign key (account_id) references bank_accounts (id),
    constraint uk_account_balances_account_date unique (account_id, balance_date)
);
create index ix_account_balances_owner on account_balances (owner_id);

-- P1: Sparen is a transfer (no category) that counts as saving
alter table transactions add column saving boolean default false not null;
alter table transactions add constraint ck_transactions_saving check (saving = false or transfer = true);

-- Saving items ticked off since AP 27c were booked as plain transfers; they are saving bookings
update transactions set saving = true where id in (
    select t.transaction_id from item_terms t join planned_items i on i.item_key = t.item_key
    where i.saving = true and t.transaction_id is not null);

alter table planned_items add column reserve_account_id bigint;
alter table planned_items
    add constraint fk_planned_items_reserve_account foreign key (reserve_account_id) references bank_accounts (id);
