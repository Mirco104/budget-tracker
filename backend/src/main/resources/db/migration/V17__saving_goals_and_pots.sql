-- P8 and concept 3.6 (AP 27e): saving goals; a saving item can belong to a goal. A booking can be paid explicitly
-- from the reserve pot of a rare item (its item key) or from a saving goal ("aus Rücklage / Ersparnissen bezahlen").
-- Never change this file once merged.

create table saving_goals (
    id            bigint generated by default as identity,
    owner_id      bigint         not null,
    name          varchar(100)   not null,
    target_amount numeric(12, 2),
    target_date   date,
    constraint pk_saving_goals primary key (id),
    constraint fk_saving_goals_owner foreign key (owner_id) references users (id)
);
create index ix_saving_goals_owner on saving_goals (owner_id);

alter table planned_items add column saving_goal_id bigint;
alter table planned_items
    add constraint fk_planned_items_saving_goal foreign key (saving_goal_id) references saving_goals (id);

alter table transactions add column reserve_item_key uuid;
alter table transactions add column saving_goal_id bigint;
alter table transactions
    add constraint fk_transactions_saving_goal foreign key (saving_goal_id) references saving_goals (id);
