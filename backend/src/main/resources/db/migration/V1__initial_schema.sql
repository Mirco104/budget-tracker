-- Initial schema (US11): the tables the entities used before Flyway, as Hibernate generated them.
-- Portable SQL for H2 (tests, local dev) and PostgreSQL (production). Never change this file once merged.

create table category (
    id         bigint generated by default as identity,
    name       varchar(100) not null,
    sort_order integer      not null,
    archived   boolean      default false not null,
    constraint pk_category primary key (id),
    constraint uk_category_name unique (name)
);

create table category_target (
    id             bigint generated by default as identity,
    category_id    bigint        not null,
    valid_from     date          not null,
    target_amount  numeric(12, 2),
    target_percent numeric(5, 4),
    constraint pk_category_target primary key (id),
    constraint uk_category_target_category_valid_from unique (category_id, valid_from),
    constraint fk_category_target_category foreign key (category_id) references category (id)
);

create table transactions (
    id           bigint generated by default as identity,
    amount       numeric(12, 2) not null,
    description  varchar(100)   not null,
    booking_date date           not null,
    category_id  bigint         not null,
    constraint pk_transactions primary key (id),
    constraint fk_transactions_category foreign key (category_id) references category (id)
);

create table recurring_transactions (
    id                  bigint generated by default as identity,
    series_id           uuid           not null,
    amount              numeric(12, 2) not null,
    description         varchar(100)   not null,
    category_id         bigint         not null,
    recurrence_interval varchar(20)    not null,
    start_date          date           not null,
    end_date            date,
    constraint pk_recurring_transactions primary key (id),
    constraint ck_recurring_transactions_interval
        check (recurrence_interval in ('MONTHLY', 'QUARTERLY', 'HALF_YEARLY', 'YEARLY')),
    constraint fk_recurring_transactions_category foreign key (category_id) references category (id)
);

create table recurring_exceptions (
    id              bigint generated by default as identity,
    recurring_id    bigint not null,
    occurrence_date date   not null,
    constraint pk_recurring_exceptions primary key (id),
    constraint uk_recurring_exceptions_recurring_date unique (recurring_id, occurrence_date),
    constraint fk_recurring_exceptions_recurring foreign key (recurring_id) references recurring_transactions (id)
);

-- PostgreSQL does not index foreign keys on its own; month queries filter by date.
create index ix_transactions_booking_date on transactions (booking_date);
create index ix_transactions_category on transactions (category_id);
create index ix_recurring_transactions_category on recurring_transactions (category_id);
