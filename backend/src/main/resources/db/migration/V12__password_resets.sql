-- Password reset links (US36, ticket #81): an admin creates a link for an account, usable once, valid for 24 hours.
-- Only the SHA-256 hash of the token is stored, so a copy of the database opens no account.
-- Never change this file once merged.

create table password_resets (
    id            bigint generated by default as identity,
    token_hash    varchar(64)              not null,
    user_id       bigint                   not null,
    created_by_id bigint                   not null,
    expires_at    timestamp with time zone not null,
    used_at       timestamp with time zone,
    constraint pk_password_resets primary key (id),
    constraint uk_password_resets_token_hash unique (token_hash),
    constraint fk_password_resets_user foreign key (user_id) references users (id),
    constraint fk_password_resets_created_by foreign key (created_by_id) references users (id)
);

create index ix_password_resets_user on password_resets (user_id);
create index ix_password_resets_created_by on password_resets (created_by_id);
