-- Invitation links (US15, AP 18b): created by an admin, usable once, valid for 7 days.
-- Never change this file once merged.

create table invitations (
    id            bigint generated by default as identity,
    token         varchar(64)              not null,
    created_by_id bigint                   not null,
    expires_at    timestamp with time zone not null,
    used_at       timestamp with time zone,
    constraint pk_invitations primary key (id),
    constraint uk_invitations_token unique (token),
    constraint fk_invitations_created_by foreign key (created_by_id) references users (id)
);

create index ix_invitations_created_by on invitations (created_by_id);
