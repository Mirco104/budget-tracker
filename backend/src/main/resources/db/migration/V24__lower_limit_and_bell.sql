-- AP 27h (decision 65, P10, P12): the lower limit of an account replaces the comfort amount; month closings and
-- dismissed notifications of the bell. Never change this file once merged.

alter table bank_accounts add column lower_limit_mode varchar(6) default 'OFF' not null;
alter table bank_accounts add column lower_limit numeric(12, 2);
update bank_accounts set lower_limit_mode = 'CUSTOM', lower_limit = comfort_amount where comfort_amount is not null;
update bank_accounts set lower_limit_mode = 'ZERO' where comfort_amount is null and role = 'EVERYDAY';
alter table bank_accounts drop column comfort_amount;
alter table bank_accounts
    add constraint ck_bank_accounts_lower_limit check (lower_limit_mode in ('OFF', 'ZERO', 'CUSTOM'));

create table month_closings (
    id             bigint generated by default as identity,
    owner_id       bigint         not null,
    closing_month  date           not null,
    amount         numeric(12, 2) not null,
    saving_goal_id bigint,
    constraint pk_month_closings primary key (id),
    constraint fk_month_closings_owner foreign key (owner_id) references users (id),
    constraint fk_month_closings_goal foreign key (saving_goal_id) references saving_goals (id),
    constraint uq_month_closings unique (owner_id, closing_month)
);

create table dismissed_notifications (
    id               bigint generated by default as identity,
    owner_id         bigint       not null,
    notification_key varchar(200) not null,
    constraint pk_dismissed_notifications primary key (id),
    constraint fk_dismissed_notifications_owner foreign key (owner_id) references users (id),
    constraint uq_dismissed_notifications unique (owner_id, notification_key)
);
