-- Users and tenant separation (R15, US14, AP 18). Every category, transaction and series belongs to one user;
-- targets and exceptions belong to a user through their category or series.
-- Data from before users existed has no owner and is deleted (decision for AP 18; production was still empty).
-- Never change this file once merged.

delete from recurring_exceptions;
delete from recurring_transactions;
delete from transactions;
delete from category_target;
delete from category;

-- "user" is reserved in PostgreSQL
create table users (
    id            bigint generated by default as identity,
    email         varchar(254)             not null,
    password_hash varchar(100)             not null,
    display_name  varchar(50)              not null,
    role          varchar(10)              not null,
    created_at    timestamp with time zone not null,
    constraint pk_users primary key (id),
    constraint uk_users_email unique (email),
    constraint ck_users_role check (role in ('USER', 'ADMIN'))
);

alter table category add column owner_id bigint not null;
alter table category add constraint fk_category_owner foreign key (owner_id) references users (id);
-- Names are unique per user (the service also ignores case)
alter table category drop constraint uk_category_name;
alter table category add constraint uk_category_owner_name unique (owner_id, name);

alter table transactions add column owner_id bigint not null;
alter table transactions add constraint fk_transactions_owner foreign key (owner_id) references users (id);
create index ix_transactions_owner_booking_date on transactions (owner_id, booking_date);

alter table recurring_transactions add column owner_id bigint not null;
alter table recurring_transactions
    add constraint fk_recurring_transactions_owner foreign key (owner_id) references users (id);
create index ix_recurring_transactions_owner on recurring_transactions (owner_id);
